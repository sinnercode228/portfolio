def _dt(d: date) -> datetime:
    return datetime(d.year, d.month, d.day)


def build_invoice(entries: list[WorkEntry], rates: list[Rate], out_path: str | Path, *,
                  lang: str = "en", period_from: date, period_to: date,
                  invoice_no: str = "2026-09-001", invoice_date: date | None = None,
                  terms_days: int = 14, increment: float = 0.25, tax_rate: float = 0.0,
                  currency: str = "USD") -> Path:
    if not rates:
        raise ValueError("rates table is empty")
    T = L10N[lang]
    S = T["sheets"]
    invoice_date = invoice_date or period_to + timedelta(days=1)

    wb = Workbook()
    ws_set = wb.active
    ws_set.title = S["settings"]
    ws_inv = wb.create_sheet(S["invoice"])
    ws_pay = wb.create_sheet(S["payroll"])
    ws_sum = wb.create_sheet(S["summary"])
    ws_log = wb.create_sheet(S["log"])
    ws_rates = wb.create_sheet(S["rates"])
    wb.move_sheet(ws_set, offset=5)          # Settings last; Invoice opens first

    values = {"invNo": invoice_no, "invDate": _dt(invoice_date), "perFrom": _dt(period_from),
              "perTo": _dt(period_to), "termsDays": terms_days, "billInc": increment,
              "taxRate": tax_rate, "currency": currency, **PARTIES[lang]}
    _rates_sheet(ws_rates, rates, T)
    _log_sheet(wb, ws_log, entries, T)
    _settings_sheet(wb, ws_set, values, T)
    subtotal_cell = _invoice_sheet(ws_inv, rates, entries, T)
    wb.defined_names["invSubtotal"] = DefinedName("invSubtotal", attr_text=f"{quote_sheet(S['invoice'])}!{subtotal_cell}")
    _payroll_sheet(ws_pay, rates, T, lang)
    _summary_sheet(ws_sum, T)

    wb.calculation = CalcProperties(fullCalcOnLoad=True)
    wb.properties.title = f"{T['invoice_word']} {invoice_no}"
    wb.properties.creator = "xldash demo (github.com/sinnercode228)"
    wb.properties.description = T["demo"]
    wb.active = wb.index(ws_inv)
    for ws in wb.worksheets:
        ws.sheet_view.tabSelected = ws is ws_inv
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(out_path)
    return out_path


