def _summary_sheet(ws, T):
    base_sheet(ws)
    set_widths(ws, {"A": 2, "B": 9, "C": 13, "D": 13, "E": 14, "F": 14, "G": 16, "H": 16, "I": 14})
    title_bar(ws, T["summary_title"], 2, 9, subtitle=T["demo"])
    cols = T["log_cols"]
    d = f"{LOG}[{cols[0]}]"
    hdr = [h if not h.endswith(", ") else f'="{h}"&currency' for h in T["sum_hdr"]]
    header_row(ws, 4, 2, hdr)
    first = 5
    for w in range(WEEKS):
        r = first + w
        start = "=perFrom" if w == 0 else f'=IF(C{r - 1}="","",IF(D{r - 1}+1>perTo,"",D{r - 1}+1))'
        rng = f'{d},">="&$C{r},{d},"<="&$D{r}'
        body_cell(ws.cell(row=r, column=2, value=f'=IF(C{r}="","",{w + 1})'), "0", align="center")
        body_cell(ws.cell(row=r, column=3, value=start), T["date_fmt"], align="center")
        body_cell(ws.cell(row=r, column=4, value=f'=IF(C{r}="","",MIN(perTo,C{r}+7-WEEKDAY(C{r},2)))'),
                  T["date_fmt"], align="center")
        body_cell(ws.cell(row=r, column=5, value=f'=IF(C{r}="","",SUMIFS({LOG}[{cols[4]}],{rng}))'), FMT_H)
        body_cell(ws.cell(row=r, column=6,
                          value=f'=IF(C{r}="","",SUMIFS({LOG}[{cols[6]}],{LOG}[{cols[5]}],yesFlag,{rng}))'), FMT_H)
        body_cell(ws.cell(row=r, column=7, value=f'=IF(C{r}="","",SUMIFS({LOG}[{cols[8]}],{rng}))'), FMT_MONEY)
        body_cell(ws.cell(row=r, column=8, value=f'=IF(C{r}="","",SUMIFS({LOG}[{cols[10]}],{rng}))'), FMT_MONEY)
        body_cell(ws.cell(row=r, column=9, value=f'=IF(C{r}="","",G{r}-H{r})'), FMT_MONEY)
    last = first + WEEKS - 1
    tot = last + 1
    for c in range(2, 10):
        cell = ws.cell(row=tot, column=c)
        cell.border = TOP_DOUBLE
        cell.fill = fill(PANEL)
        cell.font = font(10, True)
    ws.cell(row=tot, column=2, value=T["total_row"])
    for c, fmt in ((5, FMT_H), (6, FMT_H), (7, FMT_MONEY), (8, FMT_MONEY), (9, FMT_MONEY)):
        letter = ws.cell(row=tot, column=c).column_letter
        cell = ws.cell(row=tot, column=c, value=f"=SUM({letter}{first}:{letter}{last})")
        cell.number_format = fmt
    chk = tot + 1
    ws.cell(row=chk, column=2, value=T["sum_check"]).font = font(9, color=INK_2)
    ws.cell(row=chk, column=7,
            value=f'=IF(ABS(G{tot}-invSubtotal)<0.005,"{T["check_ok"]}","{T["check_bad"]}")').font = font(9, True)
    ws.conditional_formatting.add(f"G{chk}", FormulaRule(formula=[f'LEFT(G{chk},1)="✓"'],
                                                         font=Font(color=GOOD, bold=True)))
    ws.conditional_formatting.add(f"G{chk}", FormulaRule(formula=[f'LEFT(G{chk},1)="✗"'],
                                                         font=Font(color=BAD, bold=True)))
    ws.cell(row=chk + 1, column=2,
            value=f'=IF(AND(ISNUMBER(D{last}),D{last}<perTo),"{T["sum_trunc"]}","")').font = font(9, True, BAD)

    ch = BarChart()
    ch.add_data(Reference(ws, min_col=7, max_col=8, min_row=4, max_row=last), titles_from_data=True)
    ch.set_categories(Reference(ws, min_col=3, min_row=first, max_row=last))
    style_bar_chart(ch, T["chart_weeks"], horizontal=False, colors=(BLUE, ORANGE), width=17, height=8,
                    number_format="#,##0")
    ch.x_axis.number_format = T["date_fmt"]
    ch.x_axis.auto = False             # text categories: one slot per week, not a calendar axis
    ws.add_chart(ch, f"B{chk + 3}")
    ws.print_area = f"A1:I{chk + 20}"
    ws.page_setup.orientation = "landscape"
    ws.page_setup.fitToWidth = 1
    ws.sheet_properties.pageSetUpPr.fitToPage = True
