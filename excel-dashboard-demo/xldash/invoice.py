def _sumifs(col_sum: str, T, *crit: str, billable: bool = False) -> str:
    d = f"{LOG}[{T['log_cols'][0]}]"
    parts = [f"{LOG}[{col_sum}]", *crit]
    if billable:
        parts += [f"{LOG}[{T['log_cols'][5]}]", "yesFlag"]
    parts += [d, '">="&perFrom', d, '"<="&perTo']
    return f"SUMIFS({','.join(parts)})"


